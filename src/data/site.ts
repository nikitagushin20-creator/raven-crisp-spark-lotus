export function formatPrice(value: number) {
  return new Intl.NumberFormat("ru-RU").format(value) + " ₽";
}

export function lineBySlug(slug: string) {
  return lines.find((line) => line.slug === slug);
}

export function productBySlug(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function productsByLine(slug: string) {
  return products.filter((product) => product.line === slug);
}

export function filterProducts(query: string, line: string) {
  const q = query.trim().toLowerCase();
  return products.filter((product) => {
    if (line && product.line !== line) return false;
    if (!q) return true;
    const hay = `${product.title} ${product.summary} ${product.category} ${product.slug}`.toLowerCase();
    return hay.includes(q);
  });
}

export function projectBySlug(slug: string) {
  return projects.find((project) => project.slug === slug);
}

